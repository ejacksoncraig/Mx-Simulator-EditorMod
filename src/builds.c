const mx_build *mx_build_find(const char *sha256)
{
    for (size_t i = 0; i < sizeof g_builds / sizeof g_builds[0]; i++)
        if (!strcmp(g_builds[i].sha256, sha256))
            return &g_builds[i];
    return NULL;
}
