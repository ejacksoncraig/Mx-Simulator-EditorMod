"""Generate the proxy's export table from tools/exports.txt.

Every opengl32 export becomes a one-instruction stub that jumps to the real function (loaded at startup into
`real_table`), except the few the mod hooks, which point at C functions instead.

Writes into src/:
  exports_gen.h   names + count, compiled into proxy.c
  opengl32.def    export table (both toolchains)
  stubs_masm.asm  stubs for MSVC (ml64)
  stubs_gas.S     stubs for mingw-w64 (gcc)

    python tools/gen_exports.py                # from exports.txt
    python tools/gen_exports.py --from-system  # first re-read C:\\Windows\\System32\\opengl32.dll (Windows only)
"""

from __future__ import annotations

import argparse
import os
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"
EXPORTS_TXT = HERE / "exports.txt"

# Exports the mod implements itself (C functions named hook_<name> in proxy.c).
HOOKED = ("wglSwapBuffers", "glClear")
# Extra exports of the mod itself.
EXTRA = ("mxmod_version",)


def read_names(path: Path = EXPORTS_TXT) -> list[str]:
    names = [line.strip() for line in path.read_text().splitlines()]
    return [n for n in names if n and not n.startswith("#")]


def pe_export_names(dll: Path) -> list[str]:
    """Export names of a PE file in ordinal order (tiny parser, no dependencies)."""
    data = dll.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError(f"{dll} is not a PE file")
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    dd = opt + (112 if magic == 0x20B else 96)
    exp_rva, _ = struct.unpack_from("<II", data, dd)
    sections = []
    sec = opt + struct.unpack_from("<H", data, pe + 20)[0]
    for i in range(nsec):
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, sec + 40 * i + 8)
        sections.append((va, max(vsize, rsize), raw))

    def off(rva: int) -> int:
        for va, size, raw in sections:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(f"RVA {rva:#x} not in any section")

    e = off(exp_rva)
    base, nfuncs, nnames, funcs, names_rva, ords = struct.unpack_from("<IIIIII", data, e + 16)
    by_ordinal: dict[int, str] = {}
    for i in range(nnames):
        name_off = off(struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0])
        name = data[name_off:data.index(b"\0", name_off)].decode("ascii")
        by_ordinal[struct.unpack_from("<H", data, off(ords) + 2 * i)[0]] = name
    return [by_ordinal[k] for k in sorted(by_ordinal)]


def generate(names: list[str], out: Path = SRC) -> None:
    missing = [h for h in HOOKED if h not in names]
    if missing:
        raise SystemExit(f"hooked exports missing from the list: {missing}")
    out.mkdir(parents=True, exist_ok=True)
    banner = "Generated by tools/gen_exports.py from exports.txt. Do not edit."

    header = [f"/* {banner} */", "#pragma once", f"#define MXMOD_EXPORT_COUNT {len(names)}",
              "static const char *const mxmod_export_names[MXMOD_EXPORT_COUNT] = {"]
    header += [f'    "{n}",' for n in names] + ["};"]
    (out / "exports_gen.h").write_text("\n".join(header) + "\n")

    deff = [f"; {banner}", "LIBRARY opengl32", "EXPORTS"]
    for n in names:
        deff.append(f"    {n} = {'hook_' if n in HOOKED else 'stub_'}{n}")
    deff += [f"    {n}" for n in EXTRA]
    (out / "opengl32.def").write_text("\n".join(deff) + "\n")

    masm = [f"; {banner}", "EXTERN real_table:QWORD", ".code"]
    gas = [f"# {banner}", ".intel_syntax noprefix", ".text"]
    for i, n in enumerate(names):
        if n in HOOKED:
            continue
        masm += [f"stub_{n} PROC", f"    jmp QWORD PTR [real_table + {i * 8}]", f"stub_{n} ENDP"]
        gas += [f".globl stub_{n}", f"stub_{n}:", f"    jmp QWORD PTR [rip + real_table + {i * 8}]"]
    masm.append("END")
    (out / "stubs_masm.asm").write_text("\n".join(masm) + "\n")
    (out / "stubs_gas.S").write_text("\n".join(gas) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from-system", action="store_true", help="re-read System32\\opengl32.dll first")
    args = parser.parse_args()
    if args.from_system:
        dll = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "opengl32.dll"
        names = pe_export_names(dll)
        old = read_names() if EXPORTS_TXT.exists() else []
        if names != old:
            print(f"exports.txt updated: {len(old)} -> {len(names)} names")
            EXPORTS_TXT.write_text(f"# Exports of {dll} ({len(names)} names, ordinal order).\n" + "\n".join(names) + "\n")
    names = read_names()
    generate(names)
    print(f"generated {len(names)} exports ({len(HOOKED)} hooked) into {SRC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
